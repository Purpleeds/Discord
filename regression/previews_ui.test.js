// Part of the regression suites - see regression/README.md.
const { chromium } = require('playwright-core');
const http = require('http');
const BASE = require('./lib').BASE, SHOTS = require('./lib').SHOTS;
let pass = 0, fail = 0;
const check = (n, c, x) => { if (c) pass++; else { fail++; console.log('FAIL', n, x === undefined ? '' : JSON.stringify(x)); } };
const sleep = ms => new Promise(r => setTimeout(r, ms));
let hits2 = 0;
const s1 = http.createServer((req, res) => { res.writeHead(200, { 'content-type': 'text/html' }); res.end('<head><title>x</title><meta property="og:title" content="Card Title"><meta property="og:description" content="Card description text"><meta property="og:site_name" content="Example Site"><meta name="theme-color" content="#3ba55c"></head>'); });
const s2 = http.createServer((req, res) => { hits2++; res.end('<head><meta property="og:title" content="SECRET"></head>'); });
(async () => {
  await new Promise(r => s1.listen(45871, '127.0.0.1', r));
  await new Promise(r => s2.listen(45872, '127.0.0.1', r));
  const u = 'pv' + Date.now().toString(36).slice(-5);
  const okUrl = 'http://127.0.0.1:45871/ok?v=' + u;
  await fetch(BASE + '/register', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ username: u, password: 'secret123' }) });
  const browser = await chromium.launch({ executablePath: require('./lib').CHROME });
  const page = await (await browser.newContext({ viewport: { width: 1100, height: 760 } })).newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto(BASE);
  await page.fill('#username', u); await page.fill('#password', 'secret123'); await page.click('#loginCard .bigBtn');
  await page.waitForSelector('#app.ready'); await sleep(900);
  await page.fill('#messageInput', 'look at ' + okUrl + ' and http://127.0.0.1:45872/secret'); await page.press('#messageInput', 'Enter');
  await page.waitForSelector('.linkCard', { timeout: 8000 }).catch(() => {});
  await sleep(800);
  const cards = await page.$$eval('#messagesInner .message:last-child .linkCard', els => els.map(e => e.innerText));
  check('one card, for the safe link', cards.length === 1 && cards[0].includes('Card Title') && cards[0].includes('Example Site') && cards[0].includes('Card description'), cards);
  check('internal link: no card, never contacted', !JSON.stringify(cards).includes('SECRET') && hits2 === 0, hits2);
  const last = '#messagesInner .message:last-child ';
  check('card title links to the page, safely', await page.$eval(last + '.linkCard .linkCardTitle', (a, want) => a.href === want && a.target === '_blank' && a.rel.includes('noopener'), okUrl));
  check('theme colour used', await page.$eval(last + '.linkCard', el => el.style.borderLeftColor.includes('59, 165, 92')));
  await page.screenshot({ path: SHOTS + 'b4_preview.png' });
  await page.evaluate(() => setAppearance({ linkPreviews: false }, true)); await sleep(500);
  check('turning previews off hides cards', (await page.$$('.linkCard')).length === 0);
  await page.evaluate(() => setAppearance({ linkPreviews: true }, true)); await sleep(1000);
  const n = (await page.$$(last + '.linkCard')).length;
  check('and back on shows them', n === 1, n);
  check('no page errors', errors.length === 0, errors);
  await browser.close(); s1.close(); s2.close();
  console.log(`passed ${pass}, failed ${fail}`);
  process.exit(fail ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
